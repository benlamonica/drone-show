"""Show FC: the circuit, as data.

Every part, its footprint, its order code and the net on every pin lives here.
`make_schematic.py` turns this into the KiCad schematic and symbol library,
and `make_board.py` turns the same data into the board, so the two cannot
disagree. Change the circuit here, then regenerate both.

Based on OpenFC-Lite rev3.3 (RP2354B), redesigned for a 2-layer board with
0603 or larger passives, a DPS368 barometer and show-drone I/O.
"""

from dataclasses import dataclass, field

# ---------------------------------------------------------------------------
# Footprints. Standard KiCad library where it has the part, otherwise the
# project library `showfc` (generated by make_footprints.py).

R0402 = "Resistor_SMD:R_0402_1005Metric"
R0603 = "Resistor_SMD:R_0603_1608Metric"
C0402 = "Capacitor_SMD:C_0402_1005Metric"
C0603 = "Capacitor_SMD:C_0603_1608Metric"
C0805 = "Capacitor_SMD:C_0805_2012Metric"
C1206 = "Capacitor_SMD:C_1206_3216Metric"
LED0603 = "LED_SMD:LED_0603_1608Metric"


@dataclass
class Part:
    ref: str
    kind: str            # symbol in showfc.kicad_sym
    value: str
    footprint: str
    pins: dict           # pin number -> net name ("NC" = no connect)
    mpn: str = ""
    mfr: str = ""
    lcsc: str = ""
    note: str = ""
    group: str = ""      # schematic block
    fields: dict = field(default_factory=dict)


PARTS: list[Part] = []


def add(ref, kind, value, footprint, pins, group, mpn="", mfr="", lcsc="", note=""):
    PARTS.append(Part(ref, kind, value, footprint, pins, mpn, mfr, lcsc, note, group))


def R(ref, value, a, b, group, note="", size="0603"):
    mpn = f"RC{size}FR-07{value.replace('.', 'R').upper()}L"
    add(ref, "R", value, R0402 if size == "0402" else R0603, {"1": a, "2": b}, group, mpn, "Yageo", note=note)


def C(ref, value, a, b, group, size="0603", volt="", note=""):
    fp = {"0402": C0402, "0603": C0603, "0805": C0805, "1206": C1206}[size]
    v = f"{value} {volt}".strip()
    add(ref, "C", v, fp, {"1": a, "2": b}, group, mpn=CAP_MPN.get((value, size, volt), ""), mfr="Murata", note=note)


CAP_MPN = {
    ("100n", "0402", ""): "GRM155R71C104KA88D",
    ("15p", "0402", ""): "GRM1555C1H150JA01D",
    ("100n", "0603", ""): "GCM188R71H104KA57D",
    ("100n", "0603", "50V"): "GCM188R71H104KA57D",
    ("1u", "0603", ""): "GRM188R61E105KA12D",
    ("4.7u", "0603", ""): "GRM188R61A475KE15D",
    ("10u", "0805", ""): "GRM21BR61C106KE15L",
    ("10u", "1206", "50V"): "GRM31CR61H106KA12L",
    ("22u", "1206", "25V"): "GRM31CR61E226KE15L",
    ("15p", "0603", ""): "GRM1885C1H150JA01D",
}


def LED(ref, colour, anode, cathode, group):
    mpn = {"blue": "150060BS75000", "green": "150060VS75000", "red": "150060RS75000"}[colour]
    add(ref, "LED", f"LED {colour}", LED0603, {"1": cathode, "2": anode}, group, mpn, "Wurth Elektronik")


def TP(ref, net, group, size="1.5", note=""):
    add(ref, "TP", net, f"TestPoint:TestPoint_Pad_D{size}mm", {"1": net}, group, note=note)


